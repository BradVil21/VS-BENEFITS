"""Writes /shortlinks.js: partner short-link funnels + the list of real site paths
a short code may never take over. Re-run after adding new top-level pages:
    python3 .seo-work/gen_shortlinks.py
Used by middleware.js (redirects vshealthbenefits.com/<code>) and admin.html (Partners form)."""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
names = set()
for n in os.listdir(ROOT):
    p = os.path.join(ROOT, n)
    if n.startswith('.'):
        continue
    if os.path.isdir(p):
        names.add(n.lower())
    else:
        names.add(re.sub(r'\.(html?|xml|txt|js|json|png|jpe?g|webp|ico|pdf|md)$', '', n, flags=re.I).lower())
vj = json.load(open(os.path.join(ROOT, 'vercel.json')))
for r in vj.get('redirects', []) + vj.get('rewrites', []):
    seg = r.get('source', '').strip('/').split('/')[0]
    if seg and ':' not in seg and '(' not in seg:
        names.add(re.sub(r'\.html?$', '', seg).lower())
names |= {'admin', 'client', 'api', 'quote', 'blog', 'lp', 'c', 'creator', 'creators', 'login', 'logout',
          'signup', 'privacy', 'terms', 'contact', 'about', 'home', 'index', 'search', 'sitemap', 'robots',
          'favicon', 'www', 'static', 'assets', 'images', 'img', 'js', 'css', 'es', 'en', 'help', 'support',
          'careers', 'jobs', 'team', 'partners', 'partner', 'affiliate', 'affiliates', 'portal', 'account',
          '__blockcheck', '__trust', '_vercel', '_next'}
names = sorted(x for x in names if re.fullmatch(r'[a-z0-9][a-z0-9_.-]*', x))
out = '''// GENERATED by .seo-work/gen_shortlinks.py - edit the generator, not this file.
// Partner short links: vshealthbenefits.com/<code> -> the partner's quote funnel, with ?ref=<code>
// so the lead is credited to them. Shared by middleware.js (does the redirect) and
// admin.html (Partners form). RESERVED holds every real page/folder name, so a code
// can never take over a real page. Re-run the generator after adding top-level pages.

export const FUNNELS = [
  ["auto",       "Best fit for their partner type", ""],
  ["choose",     "Quote form: visitor picks individual or business", "/quote"],
  ["individual", "Individual & family quote", "/quote?type=individual"],
  ["trucking",   "Trucker / owner-operator quote", "/quote?type=individual&niche=trucking"],
  ["business",   "Small business (group) quote", "/quote?type=business"],
  ["home",       "Homepage", "/"]
];

// Partner type (admin Partners form) -> funnel used when the funnel is "auto".
export const TYPE_FUNNEL = {
  "Trucking company / carrier": "trucking",
  "Freight factoring / finance": "trucking",
  "Dispatch service": "trucking",
  "CDL school": "trucking",
  "Payroll / HR company": "business",
  "Chamber / networking group": "business",
  "Trade association": "business"
};

export function normCode(v) { return String(v || "").toLowerCase().replace(/[^a-z0-9-]/g, "").slice(0, 40); }

export function funnelFor(partner) {
  var f = partner && partner.funnel;
  if (!f || f === "auto") f = TYPE_FUNNEL[(partner && partner.type) || ""] || "choose";
  return f;
}

// Path (with ?ref=) a partner's short link goes to.
export function destFor(partner) {
  var code = normCode(partner && partner.ref), f = funnelFor(partner), path = "/quote";
  for (var i = 0; i < FUNNELS.length; i++) if (FUNNELS[i][0] === f && FUNNELS[i][2]) path = FUNNELS[i][2];
  return path + (path.indexOf("?") >= 0 ? "&" : "?") + "ref=" + encodeURIComponent(code);
}

export const RESERVED = ''' + json.dumps(names) + ''';

export function isReserved(code) { return RESERVED.indexOf(normCode(code)) >= 0; }
'''
open(os.path.join(ROOT, 'shortlinks.js'), 'w').write(out)
print(len(names), 'reserved names; cta reserved?', 'cta' in names)
